#!/usr/bin/env bash
# Checks the repo before Flux sees it. Run from anywhere: scripts/validate.sh
# CI runs the same script (.github/workflows/validate.yaml); the tool
# versions come from mise.toml.
#
# Every check runs even if an earlier one fails, so one run shows every
# problem. Exits non-zero if any check failed.
set -euo pipefail

cd "$(dirname "$0")/.."

# Kubernetes version the cluster runs, for kubeconform's built-in schemas.
KUBERNETES_VERSION="1.34.5"

failed=0
fail() { echo "  FAIL: $*"; failed=1; }
section() { echo; echo "== $*"; }

# Overlays Flux applies (clusters/stage/*.yaml point at these).
overlays=(apps/stage/* infra/controllers/stage infra/configs/stage)

section "YAML parses"
while IFS= read -r f; do
  yq eval-all 'true' "$f" >/dev/null 2>&1 || fail "$f is not valid YAML"
done < <(git ls-files '*.yaml' '*.yml')

section "Every kustomization builds"
# Bases too: a base should be valid on its own, not only through an overlay.
while IFS= read -r k; do
  d=$(dirname "$k")
  kustomize build "$d" >/dev/null 2>&1 || fail "kustomize build $d"
done < <(git ls-files '*kustomization.yaml')

section "Schemas (kubeconform, Kubernetes $KUBERNETES_VERSION + Flux CRDs)"
# Flux's own CRD schemas, at the version gotk-components.yaml was generated with,
# so HelmReleases and Kustomizations are checked against what the cluster runs.
flux_version=$(sed -n 's/^# Flux Version: v//p' clusters/stage/flux-system/gotk-components.yaml)
schemas=$(mktemp -d)
trap 'rm -rf "$schemas"' EXIT
curl -sSfL "https://github.com/fluxcd/flux2/releases/download/v${flux_version}/crd-schemas.tar.gz" \
  | tar xz -C "$schemas"
# Secrets are skipped: SOPS adds a top-level `sops:` key that strict mode
# rejects. They get their own check below.
kubeconform_args=(-strict -summary -kubernetes-version "$KUBERNETES_VERSION"
  -skip Secret
  -schema-location default
  -schema-location "$schemas/{{ .ResourceKind }}{{ .KindSuffix }}.json")
for d in "${overlays[@]}"; do
  kustomize build "$d" | kubeconform "${kubeconform_args[@]}" - \
    | sed "s|^|  $d: |" || fail "kubeconform $d"
done
kubeconform "${kubeconform_args[@]}" clusters/stage/*.yaml | sed 's|^|  clusters/stage: |' \
  || fail "kubeconform clusters/stage"

section "Images pinned as tag@sha256:digest"
# flux-system is left out: flux bootstrap generates it.
podspec='((select(.kind == "Deployment" or .kind == "DaemonSet" or .kind == "StatefulSet") | .spec.template.spec),
          (select(.kind == "CronJob") | .spec.jobTemplate.spec.template.spec))'
for d in "${overlays[@]}"; do
  while IFS= read -r img; do
    if [ -n "$img" ]; then fail "$d: unpinned image $img"; fi
  done < <(kustomize build "$d" | yq "$podspec | (.containers[], .initContainers[]?) | .image | select(test(\"@sha256:[0-9a-f]{64}$\") | not)")
  # Chart images set through HelmRelease values: a `tag` needs a digest,
  # either in the tag itself or in a `digest` next to it.
  while IFS= read -r tag; do
    if [ -n "$tag" ]; then fail "$d: HelmRelease image tag without a digest: $tag"; fi
  done < <(kustomize build "$d" | yq 'select(.kind == "HelmRelease") | .spec.values | .. | select(tag == "!!map" and has("tag")) | select(has("digest") | not) | select(.tag | test("@sha256:") | not) | .tag')
done

section "Volume mounts name a volume that exists"
# The API server rejects the pod otherwise, which fails the whole Flux Kustomization.
for d in "${overlays[@]}"; do
  while IFS= read -r v; do
    if [ -n "$v" ]; then fail "$d: volumeMount '$v' has no volume"; fi
  done < <(kustomize build "$d" | yq "$podspec | [(.containers[], .initContainers[]?).volumeMounts[]?.name] - [.volumes[]?.name] | .[]")
done

section "Secrets are SOPS-encrypted"
while IFS= read -r f; do
  yq -e 'select(.kind == "Secret") | has("sops")' "$f" >/dev/null 2>&1 \
    || { fail "$f: Secret without a sops block"; continue; }
  plain=$(yq 'select(.kind == "Secret") | (.data // {}, .stringData // {}) | to_entries[] | select(.value | test("^ENC\\[") | not) | .key' "$f")
  if [ -n "$plain" ]; then fail "$f: unencrypted values: $(paste -sd, <<<"$plain")"; fi
done < <(git grep -l '^kind: Secret' -- '*.yaml')

section "Whitespace"
# gotk-components.yaml is generated by flux bootstrap, so it's left as generated.
while IFS= read -r f; do
  if grep -qE '[[:space:]]+$' "$f"; then
    fail "$f: trailing whitespace on line(s) $(grep -nE '[[:space:]]+$' "$f" | cut -d: -f1 | paste -sd,)"
  fi
  if [ -s "$f" ] && [ -n "$(tail -c1 "$f")" ]; then fail "$f: no newline at end of file"; fi
done < <(git ls-files | grep -v 'flux-system/gotk-components.yaml')

echo
if [ "$failed" -ne 0 ]; then
  echo "Validation failed."
  exit 1
fi
echo "All checks passed."
